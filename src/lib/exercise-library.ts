export const MUSCLE_GROUPS: MuscleGroup[] = [
  'Chest',
  'Back',
  'Legs',
  'Shoulders',
  'Arms',
  'Core',
];

export function getExerciseMuscleGroup(exerciseName: string): MuscleGroup {
  const norm = exerciseName.trim().toLowerCase();
  const match = EXERCISE_LIBRARY.find((e) => e.name.toLowerCase() === norm);
  if (match) return match.category;

  if (norm.includes('press') || norm.includes('chest') || norm.includes('bench') || norm.includes('fly')) return 'Chest';
  if (norm.includes('pull') || norm.includes('row') || norm.includes('deadlift') || norm.includes('lat')) return 'Back';
  if (norm.includes('squat') || norm.includes('leg') || norm.includes('calf') || norm.includes('lunge')) return 'Legs';
  if (norm.includes('shoulder') || norm.includes('lateral') || norm.includes('overhead')) return 'Shoulders';
  if (norm.includes('curl') || norm.includes('tricep') || norm.includes('bicep') || norm.includes('arm')) return 'Arms';
  if (norm.includes('ab') || norm.includes('crunch') || norm.includes('plank')) return 'Core';

  return 'Full Body';
}

export function getExerciseImage(exerciseName: string): string | undefined {
  const norm = exerciseName.trim().toLowerCase();
  if (!norm) return undefined;
  const exact = EXERCISE_LIBRARY.find((e) => e.name.toLowerCase() === norm);
  if (exact?.imageUrl) return exact.imageUrl;

  const fuzzy = EXERCISE_LIBRARY.find(
    (e) => norm.includes(e.name.toLowerCase()) || e.name.toLowerCase().includes(norm),
  );
  if (fuzzy?.imageUrl) return fuzzy.imageUrl;

  const words = norm.split(/\s+/);
  const partial = EXERCISE_LIBRARY.find((e) => {
    const eNorm = e.name.toLowerCase();
    return words.some((w) => w.length > 3 && eNorm.includes(w));
  });
  if (partial?.imageUrl) return partial.imageUrl;

  return undefined;
}
